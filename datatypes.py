# integers
age = 23
print(age)
print(type(age))

# string
name = "mudasir"
name1 = 'mudasir hassan'
name2 = '''mudasir ahmad dar'''
print(name)
print(name1)
print(name2)
print(type(name))
print(type(name1))
print(type(name2))

# float
price = 30.98
print(price)
print(type(price))

# Boolean
isFollow = True
print(isFollow)
print(type(isFollow))

# none
x = None
print(x)
print(type(x))